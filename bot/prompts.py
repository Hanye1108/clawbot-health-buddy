def load():
    """读取 persona.yaml 并更新本模块的文案；出错时抛异常，原有文案保持不变。"""
    p = _persona.load()
    g = globals()
    g["NAME"] = p["name"]
    g["PERSONA"] = _persona.persona_prompt(p)
    g["SYSTEM_PROMPT"] = g["PERSONA"] + "\n" + RULES
    g["FEATURE_GUIDE"] = p["feature_guide"]
    g["INTRO"] = list(p["intro"]) + [p["feature_guide"]]
    g["INTRO_ASK_NAME"] = p["ask_name"]
    g["WHATS_NEW"] = p["whats_new"]
    g["QUIET_NOTICE"] = "\n\n" + p["quiet_notice"]
    r = p["reminders"]
    g["MEAL_PROMPTS"] = {k: r[k] for k in ("breakfast", "lunch", "dinner")}
    g["WATER"] = r["water"]
    g["WEIGH"] = r["weigh"]
    return p


load()
